const fs = require('node:fs/promises');
const path = require('node:path');

// UI names stay stable while assets come directly from the pinned Lucide package.
const names = {
  filter: 'sliders-horizontal',
  'sidebar-open': 'panel-left-open',
  'sidebar-close': 'panel-left-close',
  user: 'user-round',
  tag: 'tag',
  library: 'file-text',
  download: 'download',
  heart: 'heart',
  clock: 'clock',
  refresh: 'refresh-cw',
  settings: 'settings',
  search: 'search',
  grid: 'grid-2x2',
  list: 'list',
  game: 'gamepad-2',
  play: 'play',
  external: 'external-link',
  arrow: 'arrow-left',
  folder: 'folder-open',
  check: 'check',
  globe: 'globe',
  palette: 'palette',
  reset: 'rotate-ccw',
  minimize: 'minus',
  maximize: 'maximize-2',
  close: 'x',
  back: 'chevron-left',
  forward: 'chevron-right',
  save: 'save',
};

async function run() {
  const root = path.join(__dirname, '..');
  const packageDir = path.join(root, 'node_modules', 'lucide-static');
  const {version} = require(path.join(packageDir, 'package.json'));
  const dest = path.join(root, 'assets', 'icons');
  await fs.mkdir(dest, {recursive: true});
  const icons = {};
  for (const [key, file] of Object.entries(names)) {
    const original = await fs.readFile(path.join(packageDir, 'icons', file + '.svg'), 'utf8');
    if (!original.includes('<svg') || /<(script|foreignObject|image)\b|\bon\w+\s*=/i.test(original)) {
      throw Error('Unexpected SVG content: ' + file);
    }
    await fs.writeFile(path.join(dest, file + '.svg'), original, 'utf8');
    icons[key] = original.replace('<svg', '<svg aria-hidden="true" focusable="false"');
  }
  await fs.copyFile(path.join(packageDir, 'LICENSE'), path.join(dest, 'LICENSE.txt'));
  const source = `// Generated by npm run icons:build from lucide-static ${version}.\n// Source SVGs and ISC / Feather MIT notices: ../assets/icons/.\nconst icons = ${JSON.stringify(icons, null, 2)};\n\nexport function icon(name) {\n  if (!Object.hasOwn(icons, name)) throw new Error('Unknown icon: ' + name);\n  return icons[name];\n}\n`;
  await fs.writeFile(path.join(root, 'src', 'icons.js'), source, 'utf8');
  console.log(`Bundled ${Object.keys(icons).length} Lucide icons (${version}).`);
}

run().catch(error => { console.error(error); process.exitCode = 1; });
